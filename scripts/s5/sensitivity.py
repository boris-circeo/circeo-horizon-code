"""S5 sensitivity table: paired effect of every campaign variant vs its router's default config.

Usage: ``python3 scripts/s5/sensitivity.py [--md docs/s5/sensitivity_table.md]``

For each variant (router + router overrides + environment overrides) the script pairs every
finished window with the default case of the same router, seed and window, and reports:

* ``cf``     mean ship capacity factor over the variant's windows [%]
* ``delta``  mean paired difference vs the default config [percentage points]
* ``se``     standard error of that paired difference (std / sqrt(n)) [points]
* ``z``      delta / se (|z| > 2 is treated as a real effect, |z| < 1 as noise)
* ``storm45_h`` mean hours per window spent in TWS > 45 kn
* ``wall_min`` mean wall time per 30-day window [min]

Environment variants change the *truth* the ship sails in (polar scale, start point...), so their
delta mixes "the world is different" with "the router reacts differently"; the oracle row of the
same environment (when present) separates the two (``gap`` = oracle CF - router CF).
Only aggregates are written: no weather or polar data leaves ``outputs/``.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import s5lib as L  # noqa: E402


def key_of(spec):
    r = dict(spec["router"])
    name = r.pop("name")
    return (name, json.dumps(r, sort_keys=True), json.dumps(spec["env"], sort_keys=True),
            spec["seed"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", default=str(L.ROOT / "docs/s5/sensitivity_table.md"))
    a = ap.parse_args()
    runs = {}
    for p in (L.OUT / "runs").glob("*.json"):
        r = json.loads(p.read_text())
        if r.get("status") != "ok":
            continue
        k = key_of(r["spec"])
        runs.setdefault(k, {})[r["spec"]["start"]] = r

    rows = []
    for (name, rov, env, seed), byw in sorted(runs.items()):
        base = runs.get((name, "{}", "{}", seed), {})
        orc = (runs.get(("Oracle_REF_H", "{}", env, 0), {})
               or runs.get(("Oracle_REF_H", "{}", env, seed), {}))
        cf = np.array([w["cf_pct"] for w in byw.values()])
        d = np.array([byw[w]["cf_pct"] - base[w]["cf_pct"] for w in byw if w in base])
        g = np.array([orc[w]["cf_pct"] - byw[w]["cf_pct"] for w in byw if w in orc])
        n = len(d)
        se = d.std(ddof=1) / np.sqrt(n) if n > 1 else np.nan
        delta = d.mean() if n else np.nan
        rows.append(dict(
            router=name, router_ovr=rov, env_ovr=env, seed=seed, n=len(cf), cf=cf.mean(),
            delta=delta, se=se, z=(delta / se) if se and se > 0 else np.nan,
            gap=g.mean() if len(g) else np.nan,
            storm45_h=np.mean([w.get("storm45_h", np.nan) for w in byw.values()]),
            man_day=np.mean([w["manoeuvres"]["per_day"] for w in byw.values()]),
            wall_min=np.mean([w["wall_s"] for w in byw.values()]) / 60))

    def f(x, nd=1):
        return "" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"

    lines = ["# S5 sensitivity table (generated by scripts/s5/sensitivity.py)", "",
             "Mean over 30-day windows of 2015 (6 bench windows, 4 for ENS tuning). "
             "delta / se / z: paired vs the router's default config on the same windows; "
             "gap: Oracle_REF_H of the same environment minus the router.", "",
             "| router | router overrides | environment overrides | n | CF % | delta pt | se | z | "
             "gap pt | h>45 kn | man./day | wall min |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(
            f"| {r['router']} | `{r['router_ovr']}` | `{r['env_ovr']}` | {r['n']} | {f(r['cf'])} | "
            f"{f(r['delta'])} | {f(r['se'])} | {f(r['z'])} | {f(r['gap'])} | {f(r['storm45_h'])} | "
            f"{f(r['man_day'], 2)} | {f(r['wall_min'])} |")
    Path(a.md).write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} variants -> {a.md}")


if __name__ == "__main__":
    main()
